-- 1. Account-state view (SECURITY DEFINER consumers only — not granted to anon/authenticated).
CREATE OR REPLACE VIEW public.v_auth_user_state AS
SELECT
  u.user_uuid,
  u.email,
  u.tenant_id,
  u.unicorn_role,
  u.user_type,
  u.disabled,
  au.id IS NULL                           AS is_ghost,
  au.last_sign_in_at,
  au.created_at                           AS auth_created_at,
  CASE
    WHEN u.disabled IS TRUE                                   THEN 'disabled'
    WHEN au.id IS NULL                                        THEN 'ghost'
    WHEN au.last_sign_in_at IS NULL                           THEN 'invited'
    WHEN au.last_sign_in_at >= now() - interval '90 days'     THEN 'active'
    ELSE 'dormant'
  END AS account_state
FROM public.users u
LEFT JOIN auth.users au ON au.id = u.user_uuid;

REVOKE ALL ON public.v_auth_user_state FROM anon, authenticated, PUBLIC;
GRANT SELECT ON public.v_auth_user_state TO service_role;

-- 2. Jobs table
CREATE TABLE public.cohort_send_jobs (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_by            uuid NOT NULL,
  action                text NOT NULL CHECK (action IN ('activate','reset')),
  filter_json           jsonb NOT NULL DEFAULT '{}'::jsonb,
  status                text NOT NULL DEFAULT 'running'
                        CHECK (status IN ('draft','running','paused','completed','cancelled','failed','stalled')),
  cap                   int  NOT NULL DEFAULT 1000 CHECK (cap > 0 AND cap <= 1000),
  batch_size            int  NOT NULL DEFAULT 10  CHECK (batch_size > 0 AND batch_size <= 50),
  throttle_ms           int  NOT NULL DEFAULT 400 CHECK (throttle_ms >= 0 AND throttle_ms <= 5000),
  total_resolved        int  NOT NULL DEFAULT 0,
  total_planned         int  NOT NULL DEFAULT 0,
  total_sent            int  NOT NULL DEFAULT 0,
  total_skipped         int  NOT NULL DEFAULT 0,
  total_failed          int  NOT NULL DEFAULT 0,
  consecutive_failures  int  NOT NULL DEFAULT 0,
  notes                 text,
  started_at            timestamptz,
  finished_at           timestamptz,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON public.cohort_send_jobs TO authenticated;
GRANT ALL    ON public.cohort_send_jobs TO service_role;

ALTER TABLE public.cohort_send_jobs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Vivacity staff can view cohort jobs"
ON public.cohort_send_jobs FOR SELECT TO authenticated
USING (public.is_vivacity_staff(auth.uid()));

CREATE POLICY "Service role full access to cohort jobs"
ON public.cohort_send_jobs FOR ALL TO service_role
USING (true) WITH CHECK (true);

CREATE TRIGGER trg_cohort_send_jobs_updated_at
BEFORE UPDATE ON public.cohort_send_jobs
FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- 3. Items table
CREATE TABLE public.cohort_send_job_items (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id          uuid NOT NULL REFERENCES public.cohort_send_jobs(id) ON DELETE CASCADE,
  user_uuid       uuid NOT NULL,
  tenant_id       bigint,
  email           text,
  state_snapshot  text NOT NULL,
  planned_action  text NOT NULL CHECK (planned_action IN ('activate','reset','skip')),
  skip_reason     text,
  outcome         text NOT NULL DEFAULT 'pending'
                  CHECK (outcome IN ('pending','sent','skipped','failed')),
  reason          text,
  attempts        int  NOT NULL DEFAULT 0,
  locked_at       timestamptz,
  locked_by       text,
  processed_at    timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cohort_send_job_items_unique UNIQUE (job_id, user_uuid)
);

CREATE INDEX cohort_send_job_items_job_outcome_idx
  ON public.cohort_send_job_items (job_id, outcome);

CREATE INDEX cohort_send_job_items_pending_lock_idx
  ON public.cohort_send_job_items (job_id, locked_at)
  WHERE outcome = 'pending';

GRANT SELECT ON public.cohort_send_job_items TO authenticated;
GRANT ALL    ON public.cohort_send_job_items TO service_role;

