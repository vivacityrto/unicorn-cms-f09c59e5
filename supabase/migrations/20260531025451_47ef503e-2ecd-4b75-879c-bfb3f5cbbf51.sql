-- 4g. reclaim_stale_cohort_locks — pg_cron maintenance (NO sends).
CREATE OR REPLACE FUNCTION public.reclaim_stale_cohort_locks()
RETURNS int
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_count int;
BEGIN
  UPDATE public.cohort_send_job_items
  SET locked_at = NULL, locked_by = NULL
  WHERE outcome = 'pending'
    AND locked_at IS NOT NULL
    AND locked_at < now() - interval '5 minutes';
  GET DIAGNOSTICS v_count = ROW_COUNT;

  -- Mark jobs as stalled when running for >2h without progress and >0 pending.
  UPDATE public.cohort_send_jobs j
  SET status = 'stalled'
  WHERE j.status = 'running'
    AND j.started_at < now() - interval '2 hours'
    AND EXISTS (SELECT 1 FROM public.cohort_send_job_items i WHERE i.job_id = j.id AND i.outcome = 'pending')
    AND NOT EXISTS (SELECT 1 FROM public.cohort_send_job_items i WHERE i.job_id = j.id AND i.processed_at > now() - interval '15 minutes');

  RETURN v_count;
END;
$$;

REVOKE ALL ON FUNCTION public.reclaim_stale_cohort_locks() FROM PUBLIC, anon, authenticated;

-- pg_cron maintenance (DDL-equivalent: cron schedule via cron.schedule).
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname='pg_cron') THEN
    PERFORM cron.unschedule('reclaim-stale-cohort-locks')
    WHERE EXISTS (SELECT 1 FROM cron.job WHERE jobname='reclaim-stale-cohort-locks');
    PERFORM cron.schedule(
      'reclaim-stale-cohort-locks',
      '*/5 * * * *',
      $cron$ SELECT public.reclaim_stale_cohort_locks(); $cron$
    );
  END IF;
END$$;

