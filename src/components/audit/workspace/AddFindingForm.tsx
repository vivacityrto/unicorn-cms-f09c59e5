interface FunctionErrorBody {
  error?: string;
  cap?: number;
  next_available_at?: string;
}

async function readFunctionError(error: unknown): Promise<{ status: number | null; body: FunctionErrorBody | null }> {
  const context = (error as { context?: Response | { response?: Response } } | null)?.context;
  // functions-js exposes the Response directly as error.context. Keep the
  // nested fallback for older wrappers so error reporting survives upgrades.
  const response = context instanceof Response ? context : context?.response;
  if (!response) return { status: null, body: null };

  try {
    return {
      status: response.status,
      body: (await response.clone().json()) as FunctionErrorBody,
    };
  } catch {
    return { status: response.status, body: null };
  }
}

function formatNextAvailable(iso: string | undefined): string | null {
  if (!iso) return null;
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return null;
  return new Intl.DateTimeFormat(undefined, {
    day: 'numeric',
    month: 'short',
    hour: 'numeric',
    minute: '2-digit',
  }).format(date);
}

interface FindingFormValues {
  summary?: string;
  detail?: string | null;
  standard_reference?: string | null;
  regulatory_reference?: string | null;
  finding_code?: string | null;
  impact?: string | null;
  priority?: string;
}

interface CorpusChunkSummary {
  source_document: string;
  clause: string | null;
  heading: string | null;
  similarity: number;
}

interface AIDraft {
  summary: string;
  detail: string;
  standard_reference: string;
  impact: string;
  priority: string;
  suggested_corrective_action: string;
  confidence: 'high' | 'medium' | 'low';
  uncertainty_notes: string | null;
}

interface AddFindingFormProps {
  auditId: string;
  sectionId?: string;
  responseId?: string;
  defaultSummary?: string;
  defaultPriority?: string;
  isAutoGenerated?: boolean;
  mode?: 'create' | 'edit';
  initialValues?: FindingFormValues;
  /** When true and a flagged response is present, show the ✨ Draft with AI button. */
  enableAiDraft?: boolean;
  /** Auditor's free-text note from QuestionCard, passed to the AI as context. */
  auditorNote?: string;
  onSave: (finding: any) => void;
  onCancel: () => void;
}

// ─── Edit-distance (lightweight Levenshtein) ───────────────────────
function levenshtein(a: string, b: string): number {
  if (a === b) return 0;
  if (a.length === 0) return b.length;
  if (b.length === 0) return a.length;
  // Cap to keep memory bounded — we only care about a percentage.
  const maxLen = 4000;
  const aa = a.length > maxLen ? a.slice(0, maxLen) : a;
  const bb = b.length > maxLen ? b.slice(0, maxLen) : b;
  const m = aa.length;
  const n = bb.length;
  let prev = new Array(n + 1);
  let curr = new Array(n + 1);
  for (let j = 0; j <= n; j++) prev[j] = j;
  for (let i = 1; i <= m; i++) {
    curr[0] = i;
    for (let j = 1; j <= n; j++) {
      const cost = aa[i - 1] === bb[j - 1] ? 0 : 1;
      curr[j] = Math.min(prev[j] + 1, curr[j - 1] + 1, prev[j - 1] + cost);
    }
    [prev, curr] = [curr, prev];
  }
  return prev[n];
}

function editDistancePct(original: string, current: string): number {
  if (!original) return current.length === 0 ? 0 : 100;
  const dist = levenshtein(original, current);
  const denom = Math.max(original.length, current.length, 1);
  return Math.round((dist / denom) * 1000) / 10; // 1 decimal place
}

function aiBadge(label: string) {
  return (
    <span
      className="inline-flex items-center rounded-md px-1.5 py-0.5 text-[10px] font-medium"
      style={{ backgroundColor: '#7130A015', color: '#44235F', border: '1px solid #7130A040' }}
    >
      <Sparkles className="h-2.5 w-2.5 mr-1" />
      {label}
    </span>
  );
}

export function AddFindingForm({
  auditId,
  sectionId,
  responseId,
  defaultSummary = '',
  defaultPriority = 'medium',
  isAutoGenerated = false,
  mode = 'create',
  initialValues,
  enableAiDraft = false,
  auditorNote,
  onSave,
  onCancel,
}: AddFindingFormProps) {
  const [summary, setSummary] = useState(initialValues?.summary ?? defaultSummary);
  const [detail, setDetail] = useState(initialValues?.detail ?? '');
  const [regulatoryRef, setRegulatoryRef] = useState(initialValues?.regulatory_reference ?? '');
  const [impact, setImpact] = useState(initialValues?.impact ?? '');
  const [priority, setPriority] = useState(initialValues?.priority ?? defaultPriority);

  // ── AI draft state ───────────────────────────────────────────────
  const [aiStatus, setAiStatus] = useState<'idle' | 'drafting' | 'drafted' | 'error' | 'capped'>('idle');
  const [aiDraft, setAiDraft] = useState<AIDraft | null>(null);
  const [aiLogId, setAiLogId] = useState<string | null>(null);
  const [aiCorpusChunks, setAiCorpusChunks] = useState<CorpusChunkSummary[]>([]);
  const [capMessage, setCapMessage] = useState<string | null>(null);
  const [aiErrorMessage, setAiErrorMessage] = useState<string | null>(null);
  const [sourcesOpen, setSourcesOpen] = useState(false);

  const isEdit = mode === 'edit';
  const findingCode = initialValues?.finding_code || null;
  const legacyRef = initialValues?.standard_reference || null;

  // Per-field "draft" status — present when value still matches the AI draft.
  const summaryIsAiUntouched = !!aiDraft && summary === aiDraft.summary;
  const summaryIsAiEdited = !!aiDraft && summary !== aiDraft.summary && summary.trim().length > 0 && summary.includes(aiDraft.summary.slice(0, 12));
  const detailIsAiUntouched = !!aiDraft && detail === composedAiDetail(aiDraft);
  const detailIsAiEdited = !!aiDraft && detail !== composedAiDetail(aiDraft) && detail.length > 0;
  const refIsAiUntouched = !!aiDraft && regulatoryRef === aiDraft.standard_reference;
  const refIsAiEdited = !!aiDraft && regulatoryRef !== aiDraft.standard_reference && regulatoryRef.length > 0;
  const impactIsAiUntouched = !!aiDraft && impact === aiDraft.impact;
  const impactIsAiEdited = !!aiDraft && impact !== aiDraft.impact && impact.length > 0;

  function badgeFor(untouched: boolean, edited: boolean) {
    if (untouched) return aiBadge('AI draft — please review');
    if (edited) return aiBadge('AI draft — edited');
    return null;
  }

  // ── AI draft handler ─────────────────────────────────────────────
  async function handleDraftWithAI() {
    if (!responseId) {
      toast.error('Cannot draft — response not yet saved.');
      return;
    }
    setAiStatus('drafting');
    setCapMessage(null);
    setAiErrorMessage(null);
    try {
      const { data, error } = await supabase.functions.invoke('draft-finding', {
        body: {
          audit_id: auditId,
          response_id: responseId,
          auditor_note: auditorNote ?? null,
        },
      });

      if (error) {
        // FunctionsHttpError carries the Response directly in `context`.
        const { status, body } = await readFunctionError(error);
        let message = 'AI draft failed. Please try again, or write the finding manually.';
        if (status === 401) message = 'Sign in expired. Please refresh.';
        else if (status === 403) message = "You don't have access to draft for this audit.";
        else if (status === 429 && body?.cap) {
          const nextAvailable = formatNextAvailable(body.next_available_at);
          setCapMessage(
            nextAvailable
              ? `Daily AI draft limit reached. Another draft becomes available after ${nextAvailable}.`
              : body.error ?? 'Daily AI draft limit reached.',
          );
          setAiStatus('capped');
          return;
        } else if (status === 402) {
          message = 'AI credits exhausted. Top up at Settings > Workspace > Usage.';
        } else if (body?.error) {
          message = body.error;
        }
        setAiErrorMessage(message);
        toast.error(message);
        setAiStatus('error');
        return;
      }

      const draft = (data?.draft ?? null) as AIDraft | null;
      const logId = (data?.log_id ?? null) as string | null;
      const chunks = (data?.corpus_chunks_used ?? []) as CorpusChunkSummary[];
      if (!draft || !logId) {
        toast.error('AI draft returned no content.');
        setAiStatus('error');
        return;
      }

      // Populate form from the draft.
      setAiDraft(draft);
      setAiLogId(logId);
      setAiCorpusChunks(chunks);
      setSummary(draft.summary);
      setDetail(composedAiDetail(draft));
      setRegulatoryRef(draft.standard_reference);
      setImpact(draft.impact);
      if (['critical', 'high', 'medium'].includes(draft.priority)) {
        setPriority(draft.priority);
      }
      setAiStatus('drafted');
    } catch (e) {
      console.error('draft-finding invoke threw:', e);
      toast.error('AI draft failed. Please try again.');
      setAiStatus('error');
    }
  }

  // ── Save / cancel ────────────────────────────────────────────────
  function fireDecision(decision: 'accepted' | 'edited' | 'rejected') {
    if (!aiLogId || !responseId) return;
    let pct: number | null = null;
    if (decision !== 'rejected' && aiDraft) {
      const original = `${aiDraft.summary}\n\n${composedAiDetail(aiDraft)}`;
      const current = `${summary}\n\n${detail}`;
      pct = editDistancePct(original, current);
    } else if (decision === 'rejected') {
      pct = 100;
    }
    // Fire-and-forget; errors are logged server-side.
    supabase.functions
      .invoke('record-finding-decision', {
        body: {
          draft_log_id: aiLogId,
          response_id: responseId,
          decision,
          final_summary: decision === 'rejected' ? null : summary,
          final_priority: decision === 'rejected' ? null : priority,
          edit_distance_pct: pct,
        },
      })
      .catch((e) => console.warn('record-finding-decision failed:', e));
  }

  const handleSave = () => {
    if (!summary.trim()) return;
    const wasAiDrafted = !!aiDraft && !!aiLogId;

    if (isEdit) {
      onSave({
        summary: summary.trim(),
        detail: detail.trim() || null,
        regulatory_reference: regulatoryRef.trim() || null,
        impact: impact.trim() || null,
        priority,
      });
    } else {
      onSave({
        audit_id: auditId,
        section_id: sectionId || null,
        response_id: responseId || null,
        summary: summary.trim(),
        detail: detail.trim() || null,
        regulatory_reference: regulatoryRef.trim() || null,
        impact: impact.trim() || null,
        priority,
        // Mark as auto-generated when the AI was used — prop default still wins otherwise.
        is_auto_generated: wasAiDrafted ? true : isAutoGenerated,
      });
    }

    if (wasAiDrafted) {
      const original = `${aiDraft!.summary}\n\n${composedAiDetail(aiDraft!)}`;
      const current = `${summary}\n\n${detail}`;
      const pct = editDistancePct(original, current);
      fireDecision(pct === 0 ? 'accepted' : 'edited');
    }
  };

  const handleCancel = () => {
    if (aiDraft && aiLogId) fireDecision('rejected');
    onCancel();
  };

  return (
    <Card className="border-amber-200 bg-amber-50/50">
      <CardContent className="p-4 space-y-3">
        {/* AI draft affordance — only on create mode, only when caller enables it */}
        {!isEdit && enableAiDraft && responseId && (
          <div>
            {aiStatus === 'idle' && (
              <Button
                type="button"
                onClick={handleDraftWithAI}
                className="text-white"
                style={{ backgroundColor: '#7130A0' }}
                onMouseEnter={(e) => (e.currentTarget.style.backgroundColor = '#5d2683')}
                onMouseLeave={(e) => (e.currentTarget.style.backgroundColor = '#7130A0')}
              >
                <Sparkles className="mr-2 h-4 w-4" />
                Draft with AI
              </Button>
            )}
            {aiStatus === 'drafting' && (
              <div
                className="rounded-md border p-4"
                style={{ borderColor: '#7130A04D', backgroundColor: '#7130A00D' }}
              >
                <div className="flex items-center gap-3">
                  <Loader2 className="h-4 w-4 animate-spin" style={{ color: '#7130A0' }} />
                  <div>
                    <p className="text-sm font-medium" style={{ color: '#44235F' }}>
                      Drafting finding…
                    </p>
                    <p className="text-xs text-muted-foreground">
                      Reviewing the relevant Standards and Practice Guides. This typically takes 8–12 seconds.
                    </p>
                  </div>
                </div>
              </div>
            )}
            {aiStatus === 'capped' && (
              <Alert variant="default" className="border-amber-200 bg-amber-50">
                <AlertCircle className="h-4 w-4 text-amber-700" />
                <AlertDescription className="text-amber-800">
                  {capMessage ?? 'Daily AI draft limit reached.'} You can still write the finding manually.
                </AlertDescription>
              </Alert>
            )}
            {aiStatus === 'error' && (
              <Alert variant="destructive">
                <AlertCircle className="h-4 w-4" />
                <AlertTitle>AI draft could not be created</AlertTitle>
                <AlertDescription className="flex flex-col items-start gap-2">
                  <span>{aiErrorMessage ?? 'You can retry or continue writing the finding manually.'}</span>
                  <Button type="button" variant="outline" size="sm" onClick={handleDraftWithAI}>
                    <Sparkles className="mr-2 h-3.5 w-3.5" /> Retry AI draft
                  </Button>
                </AlertDescription>
              </Alert>
            )}
          </div>
        )}

        {isEdit && findingCode && (
          <div className="flex items-center gap-2">
            <Label className="text-xs">Finding code</Label>
            <span className="font-mono font-bold text-sm px-2 py-0.5 rounded bg-background border">
              {findingCode}
            </span>
            <span className="text-[10px] text-muted-foreground">(auto-generated, read-only)</span>
          </div>
        )}
        {!isEdit && (
          <div className="flex items-start gap-2 rounded-md border bg-background/60 p-2 text-xs text-muted-foreground">
            <Info className="h-3.5 w-3.5 mt-0.5 flex-shrink-0" />
            <span>
              Finding code: will be auto-generated on save (e.g. <span className="font-mono">GOV-3</span>).
            </span>
          </div>
        )}
        <div>
          <div className="flex items-center justify-between mb-1">
            <Label className="text-xs">Summary *</Label>
            {badgeFor(summaryIsAiUntouched, summaryIsAiEdited)}
          </div>
          <Input value={summary} onChange={(e) => setSummary(e.target.value)} placeholder="Finding summary..." />
        </div>
        <div>
          <div className="flex items-center justify-between mb-1">
            <Label className="text-xs">Detail</Label>
            {badgeFor(detailIsAiUntouched, detailIsAiEdited)}
          </div>
          <Textarea value={detail || ''} onChange={(e) => setDetail(e.target.value)} rows={aiDraft ? 8 : 2} />
        </div>
        <div className="grid grid-cols-2 gap-3">
          <div>
            <div className="flex items-center justify-between mb-1">
              <Label className="text-xs">Regulatory Reference</Label>
              {badgeFor(refIsAiUntouched, refIsAiEdited)}
            </div>
            <Input
              value={regulatoryRef || ''}
              onChange={(e) => setRegulatoryRef(e.target.value)}
              placeholder="e.g. Std 1.1, NC 7.2, ESOS s.22"
            />
            <p className="text-[10px] text-muted-foreground mt-1">
              SRTO 2025 clause, National Code 2018 Standard, or ESOS section.
            </p>
          </div>
          <div>
            <Label className="text-xs">Priority</Label>
            <Select value={priority} onValueChange={setPriority}>
              <SelectTrigger>
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                {PRIORITY_OPTIONS.map((o) => (
                  <SelectItem key={o.value} value={o.value}>
                    {o.label}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
          </div>
        </div>
        <div>
          <div className="flex items-center justify-between mb-1">
            <Label className="text-xs">Impact</Label>
            {badgeFor(impactIsAiUntouched, impactIsAiEdited)}
          </div>
          <Textarea value={impact || ''} onChange={(e) => setImpact(e.target.value)} rows={aiDraft ? 4 : 2} />
        </div>
        {isEdit && legacyRef && (
          <div>
            <Label className="text-xs">Legacy reference (read-only)</Label>
            <p className="text-xs text-muted-foreground italic px-2 py-1 bg-muted/50 rounded">{legacyRef}</p>
          </div>
        )}

        {/* Confidence / uncertainty card */}
        {aiDraft && aiDraft.confidence !== 'high' && (
          <Alert variant="default" className="border-amber-200 bg-amber-50">
            <AlertCircle className="h-4 w-4 text-amber-700" />
            <AlertTitle className="text-amber-900">AI confidence: {aiDraft.confidence}</AlertTitle>
            {aiDraft.uncertainty_notes && (
              <AlertDescription className="text-amber-800">{aiDraft.uncertainty_notes}</AlertDescription>
            )}
          </Alert>
        )}

        {/* Sources used */}
        {aiDraft && aiCorpusChunks.length > 0 && (
          <Collapsible open={sourcesOpen} onOpenChange={setSourcesOpen}>
            <CollapsibleTrigger asChild>
              <button
                type="button"
                className="flex items-center gap-1 text-[11px] text-muted-foreground hover:text-foreground"
              >
                <ChevronDown className={cn('h-3 w-3 transition-transform', sourcesOpen && 'rotate-180')} />
                Sources used ({aiCorpusChunks.length})
              </button>
            </CollapsibleTrigger>
            <CollapsibleContent>
              <ul className="mt-2 space-y-0.5 text-[11px] text-muted-foreground pl-4">
                {aiCorpusChunks.map((c, i) => (
                  <li key={i} className="font-mono">
                    • {c.source_document} · {c.clause ?? 'n/a'} · {c.heading ?? '—'} (similarity{' '}
                    {c.similarity.toFixed(2)})
                  </li>
                ))}
              </ul>
            </CollapsibleContent>
          </Collapsible>
        )}

        <div className="flex gap-2">
          <Button size="sm" onClick={handleSave} disabled={!summary.trim()}>
            {isEdit ? 'Update Finding' : 'Save Finding'}
          </Button>
          <Button size="sm" variant="outline" onClick={handleCancel}>
            Cancel
          </Button>
        </div>
      </CardContent>
    </Card>
  );
}

// Compose the AI's "detail + suggested corrective action" into the single
// detail textarea. Keeps persistence backward-compatible (one column) while
// surfacing both pieces to the auditor for review.
function composedAiDetail(draft: AIDraft): string {
  if (!draft.suggested_corrective_action || !draft.suggested_corrective_action.trim()) {
    return draft.detail;
  }
  return `${draft.detail}\n\nSuggested corrective action:\n${draft.suggested_corrective_action}`;
}
