#!/usr/bin/env node
/**
 * Generates src/styles/dark-safety-net.css.
 *
 * Many screens use pale Tailwind colours (bg-yellow-50, text-amber-800, border-blue-200, bg-white, bg-gray-100) that
 * only look right in light mode. Fixing each class string by hand missed the ones built from variables, config
 * objects and conditionals, and the same bug kept coming back. This file is the global net: in dark mode every one of
 * those pale classes is remapped to a dark tint, readable text colour, or theme token.
 *
 * It is deliberately weaker than anything written on purpose:
 *  - the selectors use :where(.dark), so they have the specificity of the plain class and any explicit
 *    dark:bg-... / dark:text-... on the element still wins;
 *  - the Academy learner shell is pinned to light with a .light class, so anything inside .light is left alone;
 *    put .keep-light on a surface that must stay light in dark mode (a white button on a purple banner, an email
 *    preview, a document preview);
 *  - prefixed classes (hover:bg-..., dark:bg-...) are different class names and never match.
 *
 * Run:  node scripts/generate-dark-safety-net.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'styles', 'dark-safety-net.css');

const HUES = {
  red: 0, orange: 25, amber: 38, yellow: 48, lime: 84, green: 142, emerald: 160, teal: 173, cyan: 188,
  sky: 199, blue: 217, indigo: 239, violet: 258, purple: 271, fuchsia: 292, pink: 330, rose: 350,
};
const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
const BG_SHADES = [50, 100, 200];
const TEXT_DARK = [700, 800, 900];
const TEXT_MID = [600];
const BORDER_SHADES = [100, 200, 300];
const OPACITIES = ['5', '10', '20', '25', '30', '40', '50', '60', '70', '75', '80', '90', '95'];

const NOT_LIGHT = ':not(:where(.light, .light *, .keep-light, .keep-light *))';
const rules = [];

/** A plain class, plus the same class with an opacity suffix (bg-amber-50/50). */
function bgSelector(name, opacityVariants = true) {
  const plain = `:where(.dark) .${name}${NOT_LIGHT}`;
  if (!opacityVariants) return plain;
  const withOpacity = OPACITIES.map((o) => `:where(.dark) .${name}\\/${o}${NOT_LIGHT}`);
  return [plain, ...withOpacity].join(',\n');
}
function plainSelector(name) {
  return `:where(.dark) .${name}${NOT_LIGHT}`;
}

for (const [hue, h] of Object.entries(HUES)) {
  for (const s of BG_SHADES) {
    rules.push(`${bgSelector(`bg-${hue}-${s}`)} { background-color: hsl(${h} 70% 50% / 0.15); }`);
  }
  for (const s of TEXT_DARK) rules.push(`${plainSelector(`text-${hue}-${s}`)} { color: hsl(${h} 90% 76%); }`);
  for (const s of TEXT_MID) rules.push(`${plainSelector(`text-${hue}-${s}`)} { color: hsl(${h} 85% 68%); }`);
  for (const s of BORDER_SHADES) rules.push(`${plainSelector(`border-${hue}-${s}`)} { border-color: hsl(${h} 70% 50% / 0.3); }`);
}
for (const n of NEUTRALS) {
  for (const s of BG_SHADES) rules.push(`${bgSelector(`bg-${n}-${s}`)} { background-color: hsl(var(--muted)); }`);
  for (const s of [500, 600]) rules.push(`${plainSelector(`text-${n}-${s}`)} { color: hsl(var(--muted-foreground)); }`);
  for (const s of TEXT_DARK) rules.push(`${plainSelector(`text-${n}-${s}`)} { color: hsl(var(--foreground)); }`);
  for (const s of BORDER_SHADES) rules.push(`${plainSelector(`border-${n}-${s}`)} { border-color: hsl(var(--border)); }`);
}
// Not the opacity forms: bg-white/20 is an overlay on a coloured surface, not a pale card.
rules.push(`${bgSelector('bg-white', false)} { background-color: hsl(var(--card)); }`);
rules.push(`${plainSelector('text-black')} { color: hsl(var(--foreground)); }`);

const header = `/* GENERATED by scripts/generate-dark-safety-net.mjs. Do not edit by hand; edit the generator and rerun it.
   Dark-mode safety net for pale Tailwind colours. See the generator for why it is written this way. */
`;
writeFileSync(OUT, `${header}\n${rules.join('\n\n')}\n`);
console.log(`dark safety net: ${rules.length} rules written to ${OUT.replace(/\\/g, '/')}`);
