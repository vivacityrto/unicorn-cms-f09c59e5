#!/usr/bin/env node
/**
 * Regenerates docs/kb/codebase-state/route-inventory-by-role.md's route
 * tables straight from src/App.tsx's <Route> declarations — added 2026-08-26
 * (F-024 in docs/audit-report-2026-08-26.md) because the hand-maintained
 * doc had drifted (claimed 216 routes from 2026-07-29; ~250 actual).
 *
 * This is a mechanical extraction: path, rendered component, and guard tier
 * (public / ProtectedRoute / requireSuperAdmin / allowVivacityTeam /
 * allowedRoles=<CONST>) read directly from the JSX. It does NOT attempt the
 * deeper "who should actually have this" product classification — that's
 * rbac-v6 Phase 0 (docs/kb/handoffs/rbac-v6-gate-closure-plan.md).
 *
 * Usage: node scripts/generate-route-inventory.mjs
 * Prints markdown tables to stdout, grouped by guard tier then by top-level
 * path segment. Paste into route-inventory-by-role.md's route sections and
 * update the header's route count / "last updated" / "reflects commit".
 */
import { readFileSync } from "node:fs";

const src = readFileSync(new URL("../src/App.tsx", import.meta.url), "utf8");

const routeRe = /<Route\b([^>]*?)\/?>/gs;
const results = [];
let m;
while ((m = routeRe.exec(src))) {
  const attrsText = m[1];
  const pathMatch = attrsText.match(/path=\{?["']([^"']+)["']\}?/);
  if (!pathMatch) continue;
  const path = pathMatch[1];
  const start = m.index;
  const afterOpen = src.slice(start, start + 4000);
  const nextRouteIdx = afterOpen.indexOf("\n            <Route", 20);
  const nextRouteIdx2 = afterOpen.indexOf("\n            />", 20);
  const block = afterOpen.slice(
    0,
    nextRouteIdx > 0 ? nextRouteIdx : nextRouteIdx2 > 0 ? nextRouteIdx2 + 15 : 800,
  );

  const requireSuperAdmin = /requireSuperAdmin/.test(block);
  const allowedRolesMatch = block.match(/allowedRoles=\{(\[[^\]]*\]|\w+)\}/);
  const allowVivacityTeam = /allowVivacityTeam/.test(block);
  const hasProtectedRoute = /<ProtectedRoute\b/.test(block);
  const compMatch = hasProtectedRoute
    ? block.match(/<ProtectedRoute[^>]*>\s*<(\w+)/)
    : block.match(/element=\{\s*<(\w+)/);
  const component = compMatch ? compMatch[1] : "?";

  let guard = "public";
  if (hasProtectedRoute) {
    if (requireSuperAdmin) guard = "requireSuperAdmin";
    else if (allowedRolesMatch) guard = `allowedRoles=${allowedRolesMatch[1]}`;
    else if (allowVivacityTeam) guard = "allowVivacityTeam";
    else guard = "ProtectedRoute";
  }

  results.push({ path, component, guard });
}

const seen = new Set();
const deduped = results.filter((r) => {
  const key = r.path + "|" + r.component;
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

// Flag duplicate path registrations (React Router only ever reaches the
// first match — a second registration is dead code).
const pathCounts = new Map();
for (const r of deduped) pathCounts.set(r.path, (pathCounts.get(r.path) ?? 0) + 1);
const duplicatePaths = [...pathCounts.entries()].filter(([, c]) => c > 1).map(([p]) => p);

function topSegment(path) {
  if (path === "*") return "(catch-all)";
  const seg = path.split("/").filter(Boolean)[0];
  return seg ? `/${seg}` : "/";
}

const GUARD_ORDER = [
  "public",
  "ProtectedRoute",
  "requireSuperAdmin",
  "allowVivacityTeam",
];

const byGuard = new Map();
for (const r of deduped) {
  if (!byGuard.has(r.guard)) byGuard.set(r.guard, []);
  byGuard.get(r.guard).push(r);
}
const orderedGuards = [
  ...GUARD_ORDER.filter((g) => byGuard.has(g)),
  ...[...byGuard.keys()].filter((g) => !GUARD_ORDER.includes(g)).sort(),
];

console.log(`<!-- Generated by scripts/generate-route-inventory.mjs — ${deduped.length} routes total -->\n`);

if (duplicatePaths.length > 0) {
  console.log(`> **Duplicate route registrations found (dead code — React Router only reaches the first match):** ${duplicatePaths.join(", ")}\n`);
}

for (const guard of orderedGuards) {
  const rows = byGuard.get(guard).sort((a, b) => a.path.localeCompare(b.path));
  console.log(`## ${guard} (${rows.length} routes)\n`);
  console.log("| Route segment | Route | Component |");
  console.log("|---|---|---|");
  for (const r of rows) {
    console.log(`| ${topSegment(r.path)} | \`${r.path}\` | \`${r.component}\` |`);
  }
  console.log("");
}
